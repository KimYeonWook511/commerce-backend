package com.commerce.payment.application.port.dto;

/**
 * 그 호출을 어느 자리에서 부르나. 읽기 제한 시간이 진입점마다 달라 어댑터가 이 값으로 고른다.
 *
 * <p>회원이 화면에서 기다리는 자리와 배치 스레드가 도는 자리는 기준이 다르다 — 앞은 회원을 오래
 * 붙들지 않는 것이고, 뒤는 배치 스레드를 오래 잡지 않는 것이다.
 *
 * <p>이 값은 정확성에 걸리지 않는다. 겹친 호출을 막는 것은 제한 시간이 아니라 부르기 직전 전이의
 * 낙관 락이며, 짧게 잡을수록 정상 응답까지 끊어 결과 불명이 늘 뿐이다.
 */
public enum PgCallSource {

	/** 주문 취소·승인 반려처럼 회원 요청 흐름 안에서 부른다 */
	MEMBER_REQUEST,
	/** 발송 배치와 대사가 부른다. 회원이 기다리지 않으므로 더 짧게 끊는다 */
	BATCH
}
