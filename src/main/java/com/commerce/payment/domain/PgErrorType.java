package com.commerce.payment.domain;

/**
 * 그 호출에 무슨 일이 있었나. 응답 원본으로는 역산할 수 없어 따로 담는다 — 응답을 못 읽은 경우는
 * 원본이 비어 연결이 안 된 경우와 구분되지 않는다.
 *
 * <p>판정에 쓰지 않는다. 상태 분기는 호출 직후 그 자리에서 끝나고, 이 값은 그 판단을 사후에 되짚기
 * 위해 남긴다 — 조사에서 다음에 볼 곳이 갈린다.
 */
public enum PgErrorType {

	/** 연결 자체가 안 됐다 */
	CONNECT,
	/** 보냈는데 응답을 못 읽었다 */
	TIMEOUT,
	/** 응답을 받고 상태 코드로 갈렸다 */
	HTTP,
	/** 응답을 받았는데 못 읽었다 */
	PARSE,
	/** 정상 응답 */
	NONE;

	/**
	 * 응답이 돌아왔나. 호출 기록의 응답 시각을 남길지가 이 값으로 갈린다 — 그 자리가 비어 있다는 것이
	 * "이 호출의 결과를 모른다"의 표시이고, 무엇 때문에 못 받았는지는 이 유형만이 말한다.
	 */
	public boolean responded() {
		return this != CONNECT && this != TIMEOUT;
	}
}
