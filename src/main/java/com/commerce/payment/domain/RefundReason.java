package com.commerce.payment.domain;

/**
 * 왜 생긴 환불인가. 값이 정해진 목록이며 자유 문자열이 아니다 — 회원에게 보여줄 때 승인 반려 건을
 * 거르는 기준이 이 값이라, 자유 문자열이면 그 판단이 문자열 파싱으로 흐른다.
 *
 * <p>집행 여부를 정하지 않는다. 환불 행이 만들어지는 자리가 정당한 조건과 같은 트랜잭션이라 부당한
 * 행이 아예 생기지 않기 때문이다.
 *
 * <p>요청자와 축이 다르다 — 이 값은 왜 생겼는가이고 요청자는 누가 요청했는가다. 합치면 값이 곱으로
 * 늘고, 요청자는 결제사 취소 요청에 따로 실어야 한다.
 */
public enum RefundReason {

	/** 회원이 주문을 취소했다 */
	ORDER_CANCELED,
	/** 취소된 주문에 승인이 들어와 반려한다 */
	ORDER_NOT_PAYABLE,
	/** 승인 금액이 우리 기록과 달라 반려한다 */
	AMOUNT_MISMATCH
}
