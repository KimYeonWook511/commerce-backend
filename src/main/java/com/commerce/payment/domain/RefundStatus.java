package com.commerce.payment.domain;

/**
 * 환불 사건의 생명주기. 모든 상태가 한도 계산에 더해진다 — 미결인 사건의 몫을 풀어 주면 아직 돈이
 * 안 돌아갔는데 새 환불이 끼어든다.
 *
 * <p>실패로 끝나는 종착이 없다. 주문이 취소됐으면 돈은 돌아가야 하므로 "환불하지 않기로 한다"는
 * 선택지가 없고, 자동으로 갈 수 있는 종착은 {@code SUCCEEDED} 하나다. {@code MANUAL_REVIEW}는
 * 종착이 아니라 자동 처리가 더 진행할 수 없다는 사실만 뜻한다.
 *
 * <p>첫 상태 이름이 결제와 다른 것은 기다리는 대상이 달라서다 — 결제는 회원이 결제창에서 인증하기를
 * 기다리고, 환불은 우리가 보내야 할 것을 아직 안 보냈다. 부르고 응답을 기다리는 상태와 결과를 모르는
 * 상태는 양쪽이 같은 이름을 같은 뜻으로 쓴다.
 */
public enum RefundStatus {

	/** 멱등키를 들고 다음 호출을 기다림. 아직 안 나갔음이 확실하다 */
	REQUESTED,
	/** 결제사를 호출하고 응답 대기 */
	IN_PROGRESS,
	/** 결과를 모름 */
	UNKNOWN,
	/** 환불 완료 */
	SUCCEEDED,
	/** 자동으로는 더 못 함. 사람이 처리해야 한다 */
	MANUAL_REVIEW
}
